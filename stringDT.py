#String Methods:->

#1. upper() :-> variableName.upper()
#           - It will convert all lower case to uppercase letter

# EX:->  x="python programming language"

#        x.upper()
#       o/p:-> 'PYTHON PROGRAMMING LANGUAGE'




#2.lower() :-> variableName.lower()
#           - It will convert all uppercase to lowercase letter

# EX:->    y="GOOD MORNING"
#          y.lower()
#       o/p:->  'good morning'


#3. swapcase() :->  variableName.swapcase()
#           - It will convert all upperacase-> lowercase and lowercase to uppercase
